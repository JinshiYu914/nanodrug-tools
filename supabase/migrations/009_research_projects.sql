CREATE POLICY "Profiles visible to self and project peers"
  ON user_profiles FOR SELECT
  USING (can_view_user_profile(id));

CREATE POLICY "Projects visible to members and pending participants"
  ON research_projects FOR SELECT
  USING (
    is_project_member(id)
    OR EXISTS (
      SELECT 1 FROM research_project_invitations i
      WHERE i.project_id = id AND i.status = 'pending'
        AND lower(i.invitee_email) = current_user_email()
    )
    OR EXISTS (
      SELECT 1 FROM research_project_join_requests r
      WHERE r.project_id = id AND r.requester_id = auth.uid()
    )
  );

CREATE POLICY "Members visible inside project"
  ON research_project_members FOR SELECT
  USING (is_project_member(project_id));

CREATE POLICY "Invitations visible to managers and invitee"
  ON research_project_invitations FOR SELECT
  USING (
    project_role(project_id) IN ('owner', 'admin')
    OR lower(invitee_email) = current_user_email()
  );

CREATE POLICY "Join requests visible to managers and requester"
  ON research_project_join_requests FOR SELECT
  USING (
    project_role(project_id) IN ('owner', 'admin')
    OR requester_id = auth.uid()
  );

CREATE POLICY "Activity visible to project members"
  ON project_activity FOR SELECT
  USING (is_project_member(project_id));

-- ─── Project activity writer; callable only by triggers/RPC functions ─────

CREATE OR REPLACE FUNCTION record_project_activity(
  p_project_id UUID,
  p_category TEXT,
  p_action TEXT,
  p_entity_type TEXT,
  p_entity_id TEXT,
  p_entity_name TEXT,
  p_summary TEXT,
  p_revision_from BIGINT DEFAULT NULL,
  p_revision_to BIGINT DEFAULT NULL,
  p_coalesce BOOLEAN DEFAULT FALSE
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
  v_actor_id UUID := auth.uid();
  v_email TEXT := '';
  v_name TEXT := '';
  v_recent_id BIGINT;
BEGIN
  SELECT lower(coalesce(u.email, '')),
         coalesce(u.raw_user_meta_data ->> 'display_name', '')
  INTO v_email, v_name
  FROM auth.users u WHERE u.id = v_actor_id;

  IF p_coalesce THEN
    SELECT id INTO v_recent_id
    FROM project_activity
    WHERE project_id = p_project_id
      AND actor_id IS NOT DISTINCT FROM v_actor_id
      AND action = p_action
      AND entity_type = p_entity_type
      AND entity_id IS NOT DISTINCT FROM p_entity_id
      AND last_at >= now() - interval '5 minutes'
    ORDER BY last_at DESC, id DESC
    LIMIT 1
    FOR UPDATE;
  END IF;

  IF v_recent_id IS NOT NULL THEN
    UPDATE project_activity SET
      actor_email = v_email,
      actor_display_name = v_name,
      summary = p_summary,
      entity_name = p_entity_name,
      occurrence_count = occurrence_count + 1,
      revision_to = coalesce(p_revision_to, revision_to),
      last_at = now()
    WHERE id = v_recent_id;
  ELSE
    INSERT INTO project_activity (
      project_id, category, action, actor_id, actor_email, actor_display_name,
      entity_type, entity_id, entity_name, summary,
      revision_from, revision_to
    ) VALUES (
      p_project_id, p_category, p_action, v_actor_id, v_email, v_name,
      p_entity_type, p_entity_id, p_entity_name, p_summary,
      p_revision_from, p_revision_to
    );
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION record_project_activity(UUID, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, BIGINT, BIGINT, BOOLEAN) FROM PUBLIC;

