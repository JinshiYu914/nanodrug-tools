-- Research-project collaboration: membership, scoped saved data, invitations,
-- join requests, immutable activity summaries, and project-aware RLS.

-- ─── Public user directory (email remains visible only to shared projects) ──

CREATE TABLE IF NOT EXISTS user_profiles (
  id           UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email        TEXT NOT NULL,
  display_name TEXT NOT NULL DEFAULT '',
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_user_profiles_email
  ON user_profiles (lower(email));

CREATE OR REPLACE FUNCTION sync_user_profile()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
BEGIN
  IF NEW.email IS NULL THEN
    RETURN NEW;
  END IF;
  INSERT INTO public.user_profiles (id, email, display_name, updated_at)
  VALUES (
    NEW.id,
    lower(trim(NEW.email)),
    coalesce(NEW.raw_user_meta_data ->> 'display_name', ''),
    now()
  )
  ON CONFLICT (id) DO UPDATE SET
    email = excluded.email,
    display_name = excluded.display_name,
    updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS sync_user_profile_from_auth ON auth.users;
CREATE TRIGGER sync_user_profile_from_auth
  AFTER INSERT OR UPDATE OF email, raw_user_meta_data ON auth.users
  FOR EACH ROW EXECUTE FUNCTION sync_user_profile();

INSERT INTO user_profiles (id, email, display_name)
SELECT id, lower(trim(email)), coalesce(raw_user_meta_data ->> 'display_name', '')
FROM auth.users
WHERE email IS NOT NULL
ON CONFLICT (id) DO UPDATE SET
  email = excluded.email,
  display_name = excluded.display_name,
  updated_at = now();

-- ─── Projects and membership ──────────────────────────────────────────────

CREATE TABLE research_projects (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code        TEXT NOT NULL UNIQUE CHECK (code ~ '^[0-9]{4}$'),
  name        TEXT NOT NULL CHECK (char_length(trim(name)) BETWEEN 1 AND 120),
  description TEXT NOT NULL DEFAULT '' CHECK (char_length(description) <= 1000),
  owner_id    UUID NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  status      TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived')),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE research_project_members (
  project_id UUID NOT NULL REFERENCES research_projects(id) ON DELETE CASCADE,
  user_id    UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  role       TEXT NOT NULL CHECK (role IN ('owner', 'admin', 'member')),
  joined_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (project_id, user_id)
);

CREATE UNIQUE INDEX idx_research_project_single_owner
  ON research_project_members(project_id) WHERE role = 'owner';
CREATE INDEX idx_research_project_members_user
  ON research_project_members(user_id, project_id);

CREATE TABLE research_project_invitations (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  project_id    UUID NOT NULL REFERENCES research_projects(id) ON DELETE CASCADE,
  invitee_email TEXT NOT NULL,
  inviter_id    UUID NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  status        TEXT NOT NULL DEFAULT 'pending'
                CHECK (status IN ('pending', 'accepted', 'declined', 'revoked')),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  responded_at  TIMESTAMPTZ
);

CREATE UNIQUE INDEX idx_research_project_pending_invite
  ON research_project_invitations(project_id, lower(invitee_email))
  WHERE status = 'pending';

CREATE TABLE research_project_join_requests (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  project_id   UUID NOT NULL REFERENCES research_projects(id) ON DELETE CASCADE,
  requester_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  status       TEXT NOT NULL DEFAULT 'pending'
               CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
  requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  decided_at   TIMESTAMPTZ,
  decided_by   UUID REFERENCES auth.users(id) ON DELETE SET NULL
);

CREATE UNIQUE INDEX idx_research_project_pending_request
  ON research_project_join_requests(project_id, requester_id)
  WHERE status = 'pending';

CREATE TABLE project_activity (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id           UUID NOT NULL REFERENCES research_projects(id) ON DELETE CASCADE,
  category             TEXT NOT NULL CHECK (category IN ('data', 'member')),
  action               TEXT NOT NULL,
  actor_id             UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  actor_email          TEXT NOT NULL DEFAULT '',
  actor_display_name   TEXT NOT NULL DEFAULT '',
  entity_type          TEXT NOT NULL,
  entity_id            TEXT,
  entity_name          TEXT NOT NULL DEFAULT '',
  summary              TEXT NOT NULL,
  occurrence_count     INTEGER NOT NULL DEFAULT 1,
  revision_from        BIGINT,
  revision_to          BIGINT,
  first_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_project_activity_feed
  ON project_activity(project_id, last_at DESC, id DESC);

-- ─── Authorization helpers ────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION current_user_email()
RETURNS TEXT
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, auth
AS $$
  SELECT lower(coalesce((SELECT email FROM auth.users WHERE id = auth.uid()), ''));
$$;

CREATE OR REPLACE FUNCTION project_role(p_project_id UUID)
RETURNS TEXT
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT role
  FROM research_project_members
  WHERE project_id = p_project_id AND user_id = auth.uid();
$$;

CREATE OR REPLACE FUNCTION is_project_member(p_project_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM research_project_members
    WHERE project_id = p_project_id AND user_id = auth.uid()
  );
$$;

CREATE OR REPLACE FUNCTION can_edit_project(p_project_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM research_project_members m
    JOIN research_projects p ON p.id = m.project_id
    WHERE m.project_id = p_project_id
      AND m.user_id = auth.uid()
      AND m.role IN ('owner', 'admin')
      AND p.status = 'active'
  );
$$;

CREATE OR REPLACE FUNCTION shares_project_with(p_user_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT p_user_id = auth.uid() OR EXISTS (
    SELECT 1
    FROM research_project_members mine
    JOIN research_project_members theirs
      ON theirs.project_id = mine.project_id
    WHERE mine.user_id = auth.uid() AND theirs.user_id = p_user_id
  );
$$;

CREATE OR REPLACE FUNCTION can_view_user_profile(p_user_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT shares_project_with(p_user_id) OR EXISTS (
    SELECT 1
    FROM research_project_join_requests r
    JOIN research_project_members manager ON manager.project_id = r.project_id
    WHERE r.requester_id = p_user_id AND r.status = 'pending'
      AND manager.user_id = auth.uid() AND manager.role IN ('owner', 'admin')
  );
$$;

