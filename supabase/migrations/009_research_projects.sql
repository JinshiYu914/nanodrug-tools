CREATE OR REPLACE FUNCTION create_research_project(p_name TEXT, p_description TEXT DEFAULT '')
RETURNS research_projects
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_project research_projects;
  v_code TEXT;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Not authenticated'; END IF;
  IF char_length(trim(p_name)) NOT BETWEEN 1 AND 120 THEN
    RAISE EXCEPTION 'Project name is required';
  END IF;
  LOOP
    v_code := lpad(floor(random() * 10000)::integer::text, 4, '0');
    BEGIN
      INSERT INTO research_projects (code, name, description, owner_id)
      VALUES (v_code, trim(p_name), left(coalesce(p_description, ''), 1000), auth.uid())
      RETURNING * INTO v_project;
      EXIT;
    EXCEPTION WHEN unique_violation THEN
      -- Four digits are intentionally easy to share; retry on collision.
    END;
  END LOOP;

  INSERT INTO research_project_members(project_id, user_id, role)
  VALUES (v_project.id, auth.uid(), 'owner');
  PERFORM record_project_activity(v_project.id, 'member', 'project_created',
    'project', v_project.id::text, v_project.name,
    '创建了课题「' || v_project.name || '」');
  RETURN v_project;
END;
$$;

CREATE OR REPLACE FUNCTION lookup_research_project(p_code TEXT)
RETURNS TABLE(project_id UUID, code TEXT, name TEXT, owner_name TEXT)
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT p.id, p.code, p.name,
         coalesce(up.display_name, split_part(up.email, '@', 1), '负责人')
  FROM research_projects p
  LEFT JOIN user_profiles up ON up.id = p.owner_id
  WHERE p.code = upper(trim(p_code)) AND p.status = 'active';
$$;

CREATE OR REPLACE FUNCTION invite_research_project_member(p_project_id UUID, p_email TEXT)
RETURNS research_project_invitations
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_invite research_project_invitations;
  v_email TEXT := lower(trim(p_email));
  v_existing UUID;
BEGIN
  IF project_role(p_project_id) NOT IN ('owner', 'admin') OR NOT can_edit_project(p_project_id) THEN
    RAISE EXCEPTION 'Not allowed';
  END IF;
  IF v_email !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' THEN
    RAISE EXCEPTION 'Invalid email';
  END IF;
  SELECT id INTO v_existing FROM user_profiles WHERE lower(email) = v_email;
  IF v_existing IS NOT NULL AND EXISTS (
    SELECT 1 FROM research_project_members
    WHERE project_id = p_project_id AND user_id = v_existing
  ) THEN
    RAISE EXCEPTION 'Already a member';
  END IF;
  IF EXISTS (
    SELECT 1 FROM research_project_invitations
    WHERE project_id = p_project_id AND lower(invitee_email) = v_email AND status = 'pending'
  ) THEN
    RAISE EXCEPTION 'Invitation already pending';
  END IF;
  INSERT INTO research_project_invitations(project_id, invitee_email, inviter_id)
  VALUES (p_project_id, v_email, auth.uid()) RETURNING * INTO v_invite;
  PERFORM record_project_activity(p_project_id, 'member', 'member_invited',
    'invitation', v_invite.id::text, v_email, '邀请了 ' || v_email);
  RETURN v_invite;
END;
$$;

CREATE OR REPLACE FUNCTION respond_research_project_invitation(p_invitation_id UUID, p_accept BOOLEAN)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_invite research_project_invitations;
BEGIN
  SELECT * INTO v_invite FROM research_project_invitations
  WHERE id = p_invitation_id AND status = 'pending' FOR UPDATE;
  IF NOT FOUND OR lower(v_invite.invitee_email) <> current_user_email() THEN
    RAISE EXCEPTION 'Invitation not found';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM research_projects WHERE id = v_invite.project_id AND status = 'active') THEN
    RAISE EXCEPTION 'Project is archived';
  END IF;
  IF p_accept THEN
    INSERT INTO research_project_members(project_id, user_id, role)
    VALUES (v_invite.project_id, auth.uid(), 'member')
    ON CONFLICT (project_id, user_id) DO NOTHING;
    UPDATE research_project_invitations
      SET status = 'accepted', responded_at = now() WHERE id = p_invitation_id;
    PERFORM record_project_activity(v_invite.project_id, 'member', 'invitation_accepted',
      'member', auth.uid()::text, current_user_email(), '接受邀请并加入了课题');
  ELSE
    UPDATE research_project_invitations
      SET status = 'declined', responded_at = now() WHERE id = p_invitation_id;
    PERFORM record_project_activity(v_invite.project_id, 'member', 'invitation_declined',
      'invitation', v_invite.id::text, v_invite.invitee_email, '拒绝了课题邀请');
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION request_research_project_join(p_code TEXT)
RETURNS research_project_join_requests
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_project_id UUID;
  v_request research_project_join_requests;
BEGIN
  SELECT id INTO v_project_id FROM research_projects
  WHERE code = upper(trim(p_code)) AND status = 'active';
  IF v_project_id IS NULL THEN RAISE EXCEPTION 'Project not found'; END IF;
  IF is_project_member(v_project_id) THEN RAISE EXCEPTION 'Already a member'; END IF;
  IF EXISTS (SELECT 1 FROM research_project_join_requests
             WHERE project_id = v_project_id AND requester_id = auth.uid() AND status = 'pending') THEN
    RAISE EXCEPTION 'Request already pending';
  END IF;
  INSERT INTO research_project_join_requests(project_id, requester_id)
  VALUES (v_project_id, auth.uid()) RETURNING * INTO v_request;
  PERFORM record_project_activity(v_project_id, 'member', 'join_requested',
    'join_request', v_request.id::text, current_user_email(), '申请加入课题');
  RETURN v_request;
END;
$$;

CREATE OR REPLACE FUNCTION review_research_project_join_request(p_request_id UUID, p_approve BOOLEAN)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_request research_project_join_requests;
BEGIN
  SELECT * INTO v_request FROM research_project_join_requests
  WHERE id = p_request_id AND status = 'pending' FOR UPDATE;
  IF NOT FOUND OR project_role(v_request.project_id) NOT IN ('owner', 'admin')
     OR NOT can_edit_project(v_request.project_id) THEN
    RAISE EXCEPTION 'Not allowed';
  END IF;
  UPDATE research_project_join_requests SET
    status = CASE WHEN p_approve THEN 'approved' ELSE 'rejected' END,
    decided_at = now(), decided_by = auth.uid()
  WHERE id = p_request_id;
  IF p_approve THEN
    INSERT INTO research_project_members(project_id, user_id, role)
    VALUES (v_request.project_id, v_request.requester_id, 'member')
    ON CONFLICT (project_id, user_id) DO NOTHING;
  END IF;
  PERFORM record_project_activity(v_request.project_id, 'member',
    CASE WHEN p_approve THEN 'join_approved' ELSE 'join_rejected' END,
    'join_request', v_request.id::text, '',
    CASE WHEN p_approve THEN '批准了一项加入申请' ELSE '拒绝了一项加入申请' END);
END;
$$;

CREATE OR REPLACE FUNCTION set_research_project_member_role(
  p_project_id UUID, p_user_id UUID, p_role TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE v_email TEXT;
BEGIN
  IF project_role(p_project_id) <> 'owner' OR NOT can_edit_project(p_project_id)
     OR p_role NOT IN ('admin', 'member') THEN
    RAISE EXCEPTION 'Only the owner can change administrator roles';
  END IF;
  IF p_user_id = auth.uid() OR NOT EXISTS (
    SELECT 1 FROM research_project_members
    WHERE project_id = p_project_id AND user_id = p_user_id AND role <> 'owner'
  ) THEN RAISE EXCEPTION 'Member not found'; END IF;
  UPDATE research_project_members SET role = p_role
  WHERE project_id = p_project_id AND user_id = p_user_id;
  SELECT email INTO v_email FROM user_profiles WHERE id = p_user_id;
  PERFORM record_project_activity(p_project_id, 'member', 'role_changed',
    'member', p_user_id::text, coalesce(v_email, ''),
    '将 ' || coalesce(v_email, '成员') || ' 的权限调整为' ||
    CASE WHEN p_role = 'admin' THEN '管理员' ELSE '成员' END);
END;
$$;

CREATE OR REPLACE FUNCTION remove_research_project_member(p_project_id UUID, p_user_id UUID)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE v_actor_role TEXT; v_target_role TEXT; v_email TEXT;
BEGIN
  v_actor_role := project_role(p_project_id);
  IF NOT can_edit_project(p_project_id) THEN RAISE EXCEPTION 'Project is read-only'; END IF;
  SELECT role INTO v_target_role FROM research_project_members
  WHERE project_id = p_project_id AND user_id = p_user_id;
  IF v_target_role IS NULL OR v_target_role = 'owner' THEN RAISE EXCEPTION 'Member not removable'; END IF;
  IF v_actor_role = 'owner' OR (v_actor_role = 'admin' AND v_target_role = 'member') THEN
    DELETE FROM research_project_members WHERE project_id = p_project_id AND user_id = p_user_id;
    SELECT email INTO v_email FROM user_profiles WHERE id = p_user_id;
    PERFORM record_project_activity(p_project_id, 'member', 'member_removed',
      'member', p_user_id::text, coalesce(v_email, ''),
      '移除了成员 ' || coalesce(v_email, ''));
  ELSE
    RAISE EXCEPTION 'Not allowed';
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION leave_research_project(p_project_id UUID)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE v_role TEXT;
BEGIN
  v_role := project_role(p_project_id);
  IF v_role IS NULL OR v_role = 'owner' THEN RAISE EXCEPTION 'Owner cannot leave'; END IF;
  PERFORM record_project_activity(p_project_id, 'member', 'member_left',
    'member', auth.uid()::text, current_user_email(), '离开了课题');
  DELETE FROM research_project_members WHERE project_id = p_project_id AND user_id = auth.uid();
END;
$$;

CREATE OR REPLACE FUNCTION set_research_project_archived(p_project_id UUID, p_archived BOOLEAN)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE v_name TEXT;
BEGIN
  IF project_role(p_project_id) <> 'owner' THEN RAISE EXCEPTION 'Only owner can archive'; END IF;
  UPDATE research_projects SET status = CASE WHEN p_archived THEN 'archived' ELSE 'active' END,
    updated_at = now() WHERE id = p_project_id RETURNING name INTO v_name;
  PERFORM record_project_activity(p_project_id, 'member',
    CASE WHEN p_archived THEN 'project_archived' ELSE 'project_restored' END,
    'project', p_project_id::text, v_name,
    CASE WHEN p_archived THEN '归档了课题' ELSE '恢复了课题' END);
END;
$$;

-- ─── Scope lnp_saved_items to personal or project data ────────────────────

ALTER TABLE lnp_saved_items
  ADD COLUMN IF NOT EXISTS project_id UUID REFERENCES research_projects(id) ON DELETE CASCADE,
  ADD COLUMN IF NOT EXISTS last_modified_by UUID REFERENCES auth.users(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_lnp_saved_items_project_type
  ON lnp_saved_items(project_id, type, created_at DESC);

DROP POLICY IF EXISTS "Users can read own items" ON lnp_saved_items;
DROP POLICY IF EXISTS "Users can create own items" ON lnp_saved_items;
DROP POLICY IF EXISTS "Users can update own items" ON lnp_saved_items;
DROP POLICY IF EXISTS "Users can delete own items" ON lnp_saved_items;

CREATE POLICY "Read personal or project items"
  ON lnp_saved_items FOR SELECT
  USING (
    (project_id IS NULL AND user_id = auth.uid())
    OR (project_id IS NOT NULL AND is_project_member(project_id))
  );

CREATE POLICY "Create personal or editable project items"
  ON lnp_saved_items FOR INSERT
  WITH CHECK (
    user_id = auth.uid() AND (
      project_id IS NULL OR can_edit_project(project_id)
    )
  );

CREATE POLICY "Update personal or editable project items"
  ON lnp_saved_items FOR UPDATE
  USING (
    (project_id IS NULL AND user_id = auth.uid())
    OR (project_id IS NOT NULL AND can_edit_project(project_id))
  )
  WITH CHECK (
    (project_id IS NULL AND user_id = auth.uid())
    OR (project_id IS NOT NULL AND can_edit_project(project_id))
  );

CREATE POLICY "Delete personal or editable project items"
  ON lnp_saved_items FOR DELETE
  USING (
    (project_id IS NULL AND user_id = auth.uid())
    OR (project_id IS NOT NULL AND can_edit_project(project_id))
  );

CREATE OR REPLACE FUNCTION protect_lnp_saved_item_scope()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE v_parent lnp_saved_items;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF NEW.user_id IS DISTINCT FROM OLD.user_id OR NEW.project_id IS DISTINCT FROM OLD.project_id THEN
      RAISE EXCEPTION 'Saved item scope is immutable; copy it instead';
    END IF;
  END IF;
  IF NEW.parent_id IS NOT NULL THEN
    SELECT * INTO v_parent FROM lnp_saved_items WHERE id = NEW.parent_id;
    IF NOT FOUND OR NOT v_parent.is_folder OR v_parent.type <> NEW.type
       OR v_parent.project_id IS DISTINCT FROM NEW.project_id THEN
      RAISE EXCEPTION 'Parent folder must belong to the same scope and type';
    END IF;
  END IF;
  NEW.last_modified_by := auth.uid();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS protect_lnp_saved_item_scope_trigger ON lnp_saved_items;
CREATE TRIGGER protect_lnp_saved_item_scope_trigger
  BEFORE INSERT OR UPDATE ON lnp_saved_items
  FOR EACH ROW EXECUTE FUNCTION protect_lnp_saved_item_scope();

CREATE OR REPLACE FUNCTION set_lnp_saved_item_sync_fields()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := now();
  IF NEW.data IS DISTINCT FROM OLD.data THEN
    NEW.data_revision := OLD.data_revision + 1;
  ELSE
    NEW.data_revision := OLD.data_revision;
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION audit_project_saved_item()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE v_project UUID; v_label TEXT; v_row lnp_saved_items;
BEGIN
  IF TG_OP = 'DELETE' THEN
    v_row := OLD;
  ELSE
    v_row := NEW;
  END IF;
  v_project := v_row.project_id;
  IF v_project IS NULL THEN RETURN v_row; END IF;
  v_label := CASE v_row.type
    WHEN 'formula' THEN '配方'
    WHEN 'preparation' THEN '制备参数'
    WHEN 'screening_session' THEN '配方筛选'
    WHEN 'ribogreen_result' THEN 'RiboGreen结果'
    WHEN 'tlnp_experiment' THEN 'tLNP批次'
    ELSE v_row.type END;

  IF TG_OP = 'INSERT' THEN
    PERFORM record_project_activity(v_project, 'data', 'created', v_row.type,
      v_row.id::text, v_row.name, '创建了' || v_label || '「' || v_row.name || '」',
      v_row.data_revision, v_row.data_revision, FALSE);
  ELSIF TG_OP = 'DELETE' THEN
    PERFORM record_project_activity(v_project, 'data', 'deleted', v_row.type,
      v_row.id::text, v_row.name, '删除了' || v_label || '「' || v_row.name || '」');
  ELSE
    IF NEW.data IS DISTINCT FROM OLD.data THEN
      PERFORM record_project_activity(v_project, 'data', 'updated', v_row.type,
        v_row.id::text, v_row.name, '更新了' || v_label || '「' || v_row.name || '」',
        OLD.data_revision, NEW.data_revision, TRUE);
    END IF;
    IF NEW.name IS DISTINCT FROM OLD.name THEN
      PERFORM record_project_activity(v_project, 'data', 'renamed', v_row.type,
        v_row.id::text, v_row.name, '将「' || OLD.name || '」重命名为「' || NEW.name || '」');
    END IF;
    IF NEW.parent_id IS DISTINCT FROM OLD.parent_id THEN
      PERFORM record_project_activity(v_project, 'data', 'moved', v_row.type,
        v_row.id::text, v_row.name, '移动了' || v_label || '「' || v_row.name || '」');
    END IF;
  END IF;
  RETURN v_row;
END;
$$;

DROP TRIGGER IF EXISTS audit_project_saved_item_trigger ON lnp_saved_items;
CREATE TRIGGER audit_project_saved_item_trigger
  AFTER INSERT OR UPDATE OR DELETE ON lnp_saved_items
  FOR EACH ROW EXECUTE FUNCTION audit_project_saved_item();

-- Transactional insert of an application-prepared, ID-remapped collaboration bundle.
CREATE OR REPLACE FUNCTION copy_saved_item_bundle_to_project(p_project_id UUID, p_items JSONB)
RETURNS SETOF lnp_saved_items
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE v JSONB; v_source lnp_saved_items; v_created lnp_saved_items; v_type TEXT;
        v_count INTEGER := 0;
BEGIN
  IF NOT can_edit_project(p_project_id) THEN RAISE EXCEPTION 'Not allowed'; END IF;
  IF jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'Copy bundle is empty';
  END IF;
  FOR v IN SELECT value FROM jsonb_array_elements(p_items)
  LOOP
    v_type := v ->> 'type';
    IF v_type NOT IN ('formula', 'preparation', 'screening_session', 'ribogreen_result', 'tlnp_experiment') THEN
      RAISE EXCEPTION 'Unsupported shared item type';
    END IF;
    SELECT * INTO v_source FROM lnp_saved_items
    WHERE id = (v ->> 'source_id')::uuid
      AND user_id = auth.uid() AND project_id IS NULL AND type = v_type;
    IF NOT FOUND THEN RAISE EXCEPTION 'Source item is unavailable'; END IF;
    INSERT INTO lnp_saved_items (
      id, user_id, project_id, type, is_folder, parent_id, name, data, sort_order
    ) VALUES (
      (v ->> 'id')::uuid, auth.uid(), p_project_id, v_type, FALSE, NULL,
      coalesce(nullif(trim(v ->> 'name'), ''), v_source.name),
      v -> 'data', coalesce((v ->> 'sort_order')::integer, 0)
    ) RETURNING * INTO v_created;
    v_count := v_count + 1;
    RETURN NEXT v_created;
  END LOOP;
  PERFORM record_project_activity(p_project_id, 'data', 'bundle_copied',
    'copy_bundle', NULL, '', '复制了一组关联数据（' || v_count || ' 条记录）');
END;
$$;

CREATE OR REPLACE FUNCTION copy_saved_item_bundle_to_personal(p_items JSONB)
RETURNS SETOF lnp_saved_items
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE v JSONB; v_source lnp_saved_items; v_created lnp_saved_items; v_type TEXT;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Not authenticated'; END IF;
  IF jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'Copy bundle is empty';
  END IF;
  FOR v IN SELECT value FROM jsonb_array_elements(p_items)
  LOOP
    v_type := v ->> 'type';
    IF v_type NOT IN ('formula', 'preparation', 'screening_session', 'ribogreen_result', 'tlnp_experiment') THEN
      RAISE EXCEPTION 'Unsupported shared item type';
    END IF;
    SELECT * INTO v_source FROM lnp_saved_items
    WHERE id = (v ->> 'source_id')::uuid AND type = v_type
      AND project_id IS NOT NULL AND is_project_member(project_id);
    IF NOT FOUND THEN RAISE EXCEPTION 'Source item is unavailable'; END IF;
    INSERT INTO lnp_saved_items (
      id, user_id, project_id, type, is_folder, parent_id, name, data, sort_order
    ) VALUES (
      (v ->> 'id')::uuid, auth.uid(), NULL, v_type, FALSE, NULL,
      coalesce(nullif(trim(v ->> 'name'), ''), v_source.name),
      v -> 'data', coalesce((v ->> 'sort_order')::integer, 0)
    ) RETURNING * INTO v_created;
    RETURN NEXT v_created;
  END LOOP;
END;
$$;

